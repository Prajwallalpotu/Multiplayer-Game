import {test} from "node:test";
import assert from "node:assert/strict";
import {action,newRoom,addPlayer,view,type Player} from "../server/game.ts";
import {newHandsOn,pipesSolved} from "../shared/handsOn.ts";
import {Store} from "../server/store.ts";
let seq=0;
test("physical puzzle trail validates proximity and prerequisites, shares rewards, and survives save/load",()=>{
  const r=newRoom("Hands on","A"),a=r.players[0],b=addPlayer(r,"B");
  r.status="playing"; r.solved=["p01","p02"];a.laptop=b.laptop=true;
  const send=(p:Player,data:any)=>action(r,p,"laptop",{id:"hands-"+ ++seq,type:"handsOn",...data});
  assert.throws(()=>send(a,{puzzle:"frame",tile:0}),/Approach/);
  a.location="clinic";a.x=27;a.y=70;
  assert.throws(()=>send(a,{puzzle:"cupboard",code:"3142"}),/archive picture/);
  a.location="clock";a.x=29;
  assert.throws(()=>send(a,{puzzle:"music",operation:"insertKey"}),/winding key/);
  a.location="archive";a.x=28;a.y=68;
  assert.throws(()=>send(a,{puzzle:"frame",tile:9}),/puzzle tile/);
  for(let i=0;i<4;i++)for(let n=0;n<(4-newHandsOn().frame[i])%4;n++)send(a,{puzzle:"frame",tile:i});
  assert(view(r,b,"laptop").handsOn?.opened.includes("frame"));
  b.location="clinic";b.x=27;b.y=70;
  assert.throws(()=>send(b,{puzzle:"cupboard",code:"0000"}),/latch stays shut/);
  send(b,{puzzle:"cupboard",code:"3142"});
  a.location="clock";a.x=29;a.y=70;
  assert.throws(()=>send(a,{puzzle:"music",tile:0}),/Insert/);
  send(a,{puzzle:"music",operation:"insertKey"});
  for(let i=0;i<9;i++)for(let n=0;n<(4-newHandsOn().pipes[i])%4;n++)send(a,{puzzle:"music",tile:i});
  assert(r.handsOn?.opened.includes("music"));
  assert.equal(pipesSolved(r.handsOn!.pipes),true);
  assert.equal(pipesSolved(newHandsOn().pipes),false);
  const store=new Store(":memory:");store.save(r);
  assert.deepEqual(store.load()[0].handsOn,r.handsOn);store.close();
  const before=[...r.handsOn!.opened];send(a,{puzzle:"music",tile:0});assert.deepEqual(r.handsOn!.opened,before);
  assert.deepEqual(r.solved,["p01","p02"],"Optional puzzles do not skip story deductions or alter ranked rules");
});
test("save-and-exit is host-only and retains the case",()=>{
  const r=newRoom("Save","Host",true),host=r.players[0],guest=addPlayer(r,"Guest");r.status="playing";r.shared=["perimeter"];
  assert.throws(()=>action(r,guest,"laptop",{id:"exit-guest",type:"endSession"}),/Only the room creator/);
  action(r,host,"laptop",{id:"exit-host",type:"endSession"});
  assert.equal(r.manualPause,true);assert.equal(r.public,false);assert.equal(r.status,"playing");assert.deepEqual(r.shared,["perimeter"]);
});
